export function known(value: JsonValue): JsonObject {
  return {
    state: "known",
    value,
    source_bindings: [DIRECT_BINDING],
    derivation_bindings: [],
    missing_reason: null,
    provenance_status: "complete",
  };
}

export function missing(
  state: "unknown" | "not_applicable" | "withheld",
  reason: string,
): JsonObject {
  return {
    state,
    value: null,
    source_bindings: [],
    derivation_bindings: [],
    missing_reason: reason,
    provenance_status: "absent",
    ...(state === "not_applicable" ? { applicability_decision_id: FIELD_APPLICABILITY_DECISION_ID } : {}),
    ...(state === "withheld"
      ? {
          withholding_reason_code: "source_confidentiality",
          disclosure_decision_id: "disclosure:renderer-fixture",
        }
      : {}),
  };
}

