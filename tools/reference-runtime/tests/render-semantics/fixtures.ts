export function allIdentifierValues(value: JsonValue): string[] {
  const identifiers = new Set<string>();
  const visit = (current: JsonValue, key: string | null): void => {
    if (typeof current === "string") {
      if (key !== null && (key === "report_id" || key.endsWith("_id"))) {
        identifiers.add(current);
      }
      return;
    }
    if (Array.isArray(current)) {
      current.forEach((item) => visit(item, key));
      return;
    }
    if (current === null || typeof current !== "object") return;
    Object.entries(current).forEach(([childKey, child]) => {
      if (childKey.endsWith("_ids") && Array.isArray(child)) {
        child.forEach((item) => {
          if (typeof item === "string") identifiers.add(item);
        });
      } else {
        visit(child, childKey);
      }
    });
  };
  visit(value, null);
  return [...identifiers].sort((left, right) => left.localeCompare(right, "en"));
}
